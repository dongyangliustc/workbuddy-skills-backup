"""交付层：把像素级提取结果换算为数据坐标，并输出 CSV / XLSX / JSON。"""

from __future__ import annotations

import csv
import json
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Sequence

from .calibration import Calibration
from .extract import Series

TOOL_NAME = "chart-digitizer"


@dataclass
class DigitizedSeries:
    """已换算到数据坐标的序列。"""

    name: str
    kind: str
    color: tuple[int, int, int]
    x: list[float] = field(default_factory=list)
    y: list[float] = field(default_factory=list)
    yerr_low: list[float] | None = None
    yerr_high: list[float] | None = None
    meta: dict = field(default_factory=dict)

    @property
    def n(self) -> int:
        return len(self.x)

    def to_dict(self) -> dict:
        d = {
            "name": self.name,
            "kind": self.kind,
            "color": list(self.color),
            "n_points": self.n,
            "x": [round(v, 10) for v in self.x],
            "y": [round(v, 10) for v in self.y],
        }
        if self.yerr_low is not None:
            d["yerr_low"] = [round(v, 10) for v in self.yerr_low]
            d["yerr_high"] = [round(v, 10) for v in self.yerr_high or []]
        if self.meta:
            d["meta"] = self.meta
        return d


def digitize(
    series: Sequence[Series],
    calib: Calibration,
    sort_by_x: bool = True,
) -> list[DigitizedSeries]:
    """把像素坐标序列换算为数据坐标序列。"""
    out: list[DigitizedSeries] = []
    for s in series:
        pix = s.sorted_points() if sort_by_x else list(s.points)
        xs: list[float] = []
        ys: list[float] = []
        for px, py in pix:
            dx, dy = calib.to_data(px, py)
            xs.append(dx)
            ys.append(dy)

        lo = hi = None
        if s.yerr is not None:
            order = sorted(range(len(s.points)), key=lambda i: s.points[i][0]) if sort_by_x \
                else list(range(len(s.points)))
            lo, hi = [], []
            for i in order:
                px, py = s.points[i]
                down, up = s.yerr[i]
                _, y_lo = calib.to_data(px, py + down)
                _, y_hi = calib.to_data(px, py - up)
                lo.append(abs(y_lo - calib.to_data(px, py)[1]))
                hi.append(abs(y_hi - calib.to_data(px, py)[1]))

        out.append(
            DigitizedSeries(
                name=s.name, kind=s.kind, color=s.color,
                x=xs, y=ys, yerr_low=lo, yerr_high=hi, meta=dict(s.meta),
            )
        )
    return out


# ------------------------------------------------------------------ CSV


def write_csv(
    series: Sequence[DigitizedSeries],
    out: str | Path,
    source: str = "",
    calib: Calibration | None = None,
    delimiter: str = ",",
    comment: str = "#",
    audit=None,
    legend=None,
) -> list[Path]:
    """写出 CSV。多序列时按序列拆分为独立文件。

    ``audit`` 为 :class:`~chartdigit.audit.CalibrationAudit`，给出时把标定审核块写入
    文件头部（在数据之前、紧接来源行），使其无法被忽略。

    ``legend`` 为 :class:`~chartdigit.legend.LegendInfo`，给出时在其后追加「图例」区块
    （条目名、hex、``kind_hint``、来源、颜色校验结果、回退说明）。与标定审核同理：
    写在数据之前、固定区块，使它无法被忽略。
    """
    out_p = Path(out)
    written: list[Path] = []

    if len(series) == 1 and out_p.suffix.lower() == ".csv":
        targets = [out_p]
    else:
        base = out_p.with_suffix("") if out_p.suffix.lower() == ".csv" else out_p
        targets = [Path(f"{base}_{_slug(s.name)}.csv") for s in series]

    for s, tgt in zip(series, targets):
        tgt.parent.mkdir(parents=True, exist_ok=True)
        with tgt.open("w", newline="", encoding="utf-8-sig") as fh:
            w = csv.writer(fh, delimiter=delimiter)
            if source:
                fh.write(f"{comment} source: {source}\n")
            if audit is not None:
                for ln in audit.render():
                    fh.write(f"{comment} {ln}\n")
            if legend is not None:
                for ln in legend_csv_lines(legend, comment=comment):
                    fh.write(ln + "\n")
            fh.write(f"{comment} series: {s.name}  kind: {s.kind}  points: {s.n}\n")
            if calib is not None:
                b = calib.box()
                fh.write(
                    f"{comment} calibration: x=[{calib.xmin.value:g}, {calib.xmax.value:g}] "
                    f"y=[{calib.ymin.value:g}, {calib.ymax.value:g}] "
                    f"scale=({calib.xscale},{calib.yscale}) "
                    f"box_px=({b[0]:.0f},{b[1]:.0f},{b[2]:.0f},{b[3]:.0f})\n"
                )
            fh.write(f"{comment} generated by {TOOL_NAME} at "
                     f"{datetime.now(timezone.utc).astimezone().isoformat(timespec='seconds')}\n")
            header = ["x", "y"]
            if s.yerr_low is not None:
                header += ["yerr_low", "yerr_high"]
            w.writerow(header)
            for i in range(s.n):
                row = [s.x[i], s.y[i]]
                if s.yerr_low is not None:
                    row += [s.yerr_low[i], s.yerr_high[i] if s.yerr_high else ""]
                w.writerow([_num(v) for v in row])
        written.append(tgt)
    return written


# ------------------------------------------------------------------ XLSX


def write_xlsx(
    series: Sequence[DigitizedSeries],
    out: str | Path,
    source: str = "",
    calib: Calibration | None = None,
    report: dict | None = None,
    audit=None,
    legend=None,
) -> Path:
    """写出多 Sheet 工作簿：首张为元数据，其后每序列一张。

    ``audit`` 为 :class:`~chartdigit.audit.CalibrationAudit`，给出时在元数据表中加入
    「标定审核」区块（尺度绝对值、来源、几何校验结论、人工确认状态），使审核结论随
    数据一同传递，而不是只停留在终端输出里。

    ``legend`` 为 :class:`~chartdigit.legend.LegendInfo`，同样在元数据表中加入
    「图例」区块。
    """
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    out_p = Path(out)
    if out_p.suffix.lower() not in (".xlsx", ".xlsm"):
        out_p = out_p.with_suffix(".xlsx")
    out_p.parent.mkdir(parents=True, exist_ok=True)

    wb = Workbook()
    meta = wb.active
    meta.title = "Metadata"
    bold = Font(bold=True)
    head_fill = PatternFill("solid", fgColor="DCE6F1")

    meta["A1"] = "chart-digitizer 提取元数据"
    meta["A1"].font = Font(bold=True, size=13)
    rows: list[tuple[str, object]] = [
        ("生成时间", datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds")),
        ("源图像", source),
        ("序列数量", len(series)),
    ]
    if calib is not None:
        b = calib.box()
        rows += [
            ("x 范围", f"[{calib.xmin.value:g}, {calib.xmax.value:g}]"),
            ("y 范围", f"[{calib.ymin.value:g}, {calib.ymax.value:g}]"),
            ("尺度类型", f"x={calib.xscale}, y={calib.yscale}"),
            ("数据区像素", f"({b[0]:.0f}, {b[1]:.0f}) - ({b[2]:.0f}, {b[3]:.0f})"),
            ("锚点 Xmin", f"({calib.xmin.px:.0f},{calib.xmin.py:.0f}) -> {calib.xmin.value:g}"),
            ("锚点 Xmax", f"({calib.xmax.px:.0f},{calib.xmax.py:.0f}) -> {calib.xmax.value:g}"),
            ("锚点 Ymin", f"({calib.ymin.px:.0f},{calib.ymin.py:.0f}) -> {calib.ymin.value:g}"),
            ("锚点 Ymax", f"({calib.ymax.px:.0f},{calib.ymax.py:.0f}) -> {calib.ymax.value:g}"),
            ("轴倾斜(度)", round(calib.skew_degrees, 4)),
        ]
    for k, v in rows:
        r = meta.max_row + 1
        meta.cell(r, 1, k).font = bold
        meta.cell(r, 2, v)

    if audit is not None:
        r = meta.max_row + 2
        meta.cell(r, 1, "标定审核（请人工确认后使用）").font = Font(bold=True, size=12)
        for k, v in _audit_rows(audit):
            r = meta.max_row + 1
            meta.cell(r, 1, k).font = bold
            c = meta.cell(r, 2, v)
            c.alignment = Alignment(wrap_text=True, vertical="top")
        if audit.warnings:
            warn_fill = PatternFill("solid", fgColor="FFF2CC")
            for i in range(len(audit.warnings)):
                meta.cell(meta.max_row - len(audit.warnings) + 1 + i, 2).fill = warn_fill

    if legend is not None:
        r = meta.max_row + 2
        meta.cell(r, 1, _LEGEND_TITLE).font = Font(bold=True, size=12)
        r = meta.max_row + 1
        meta.cell(r, 1, legend_header(legend)).font = bold
        meta.cell(r, 2, legend_source_text(legend))
        for k, v in legend_rows(legend):
            r = meta.max_row + 1
            meta.cell(r, 1, k).font = bold
            c = meta.cell(r, 2, v)
            c.alignment = Alignment(wrap_text=True, vertical="top")
        if _legend_failed(legend):
            warn_fill = PatternFill("solid", fgColor="FFF2CC")
            for row_i in range(meta.max_row - len(legend_rows(legend)) + 1,
                               meta.max_row + 1):
                meta.cell(row_i, 2).fill = warn_fill

    if report:
        r = meta.max_row + 2
        meta.cell(r, 1, "检测报告").font = bold
        for k, v in report.items():
            r = meta.max_row + 1
            meta.cell(r, 1, str(k))
            meta.cell(r, 2, json.dumps(v, ensure_ascii=False) if isinstance(v, (dict, list)) else v)

    r = meta.max_row + 2
    meta.cell(r, 1, "序列清单").font = bold
    for i, s in enumerate(series, start=1):
        r = meta.max_row + 1
        meta.cell(r, 1, f"#{i}")
        meta.cell(r, 2, s.name)
        meta.cell(r, 3, s.kind)
        meta.cell(r, 4, s.n)
    meta.column_dimensions["A"].width = 16
    meta.column_dimensions["B"].width = 60

    for s in series:
        ws = wb.create_sheet(_sheet_name(s.name, wb.sheetnames))
        header = ["x", "y"] + (["yerr_low", "yerr_high"] if s.yerr_low is not None else [])
        ws.append(header)
        for c in range(1, len(header) + 1):
            ws.cell(1, c).font = bold
            ws.cell(1, c).fill = head_fill
            ws.cell(1, c).alignment = Alignment(horizontal="center")
        for i in range(s.n):
            row = [s.x[i], s.y[i]]
            if s.yerr_low is not None:
                row += [s.yerr_low[i], s.yerr_high[i] if s.yerr_high else None]
            ws.append(row)
        for col in "ABCD":
            ws.column_dimensions[col].width = 16

    wb.save(out_p)
    return out_p


# ------------------------------------------------------------------ JSON


def write_json(
    series: Sequence[DigitizedSeries],
    out: str | Path,
    source: str = "",
    calib: Calibration | None = None,
    report: dict | None = None,
    params: dict | None = None,
    audit=None,
    legend=None,
) -> Path:
    """写出包含完整溯源信息的 JSON。

    ``audit`` 为 :class:`~chartdigit.audit.CalibrationAudit`，给出时以 ``scale_audit``
    字段嵌入，其中 ``reviewed_by_human`` / ``ready_for_downstream`` 构成下游调用的
    机器可判定准入条件。

    ``legend`` 为 :class:`~chartdigit.legend.LegendInfo`，给出时以 ``legend`` 字段嵌入
    （结构见 SPEC §3.2.5）：条目名、hex、``kind_hint``、来源、颜色校验结果、回退说明。
    """
    out_p = Path(out)
    if out_p.suffix.lower() != ".json":
        out_p = out_p.with_suffix(".json")
    out_p.parent.mkdir(parents=True, exist_ok=True)
    payload = {
        "tool": TOOL_NAME,
        "generated_at": datetime.now(timezone.utc).astimezone().isoformat(timespec="seconds"),
        "source_image": source,
        "series": [s.to_dict() for s in series],
    }
    if calib is not None:
        payload["calibration"] = calib.to_dict()
        payload["calibration_check"] = calib.verify()
    if audit is not None:
        payload["scale_audit"] = audit.to_dict()
    if legend is not None:
        payload["legend"] = _legend_dict(legend)
    if params:
        payload["extraction_params"] = params
    if report:
        payload["detection_report"] = report
    out_p.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return out_p


# ------------------------------------------------------------------ 图例区块


#: XLSX 元数据表中的图例区块标题（测试据此定位行）
_LEGEND_TITLE = "图例（来自文献 PDF，非强制）"


def _legend_dict(legend) -> dict:
    return legend.to_dict() if hasattr(legend, "to_dict") else dict(legend)


def _legend_failed(legend) -> bool:
    d = _legend_dict(legend)
    if not d.get("found"):
        return False                       # 未检出不算失败（可选增强）
    return not (d.get("color_check") or {}).get("ok", False)


def legend_source_text(legend) -> str:
    d = _legend_dict(legend)
    if not d.get("found"):
        return "未检出（图例是可选增强，已按原行为继续）"
    return ("PDF 文本层 + 矢量对象" if d.get("source") == "pdf-text+vector"
            else "PDF 文本层（未关联到矢量色块）")


def legend_rows(legend) -> list[tuple[str, object]]:
    """图例区块 → ``(字段, 值)`` 行。**CSV 与 XLSX 共用同一份渲染**，避免两处漂移。

    覆盖 SPEC §3.2.5 要求的全部要素：条目名、hex、``kind_hint``、来源、颜色校验结果、
    校验失败时的回退说明。
    """
    d = _legend_dict(legend)
    rows: list[tuple[str, object]] = []
    if not d.get("found"):
        rows.append(("说明", d.get("note") or "未检出图例"))
        return rows

    chk = d.get("color_check") or {}
    if chk.get("ok"):
        rows.append(("颜色校验", "通过（命中 "
                     f"{chk.get('matched', 0)}/{chk.get('checked', 0)}，"
                     f"tol={chk.get('tol', 0):g}，min_pixels={chk.get('min_pixels', 0)}）"))
        rows.append(("配色", "采用图例颜色；序列名称为「名称 + hex」以便核对"))
    else:
        rows.append(("颜色校验", "**未通过** —— 已回退自动配色"
                     + (f"（{chk.get('reason')}）" if chk.get("reason") else "")))

    for i, e in enumerate(d.get("entries", []), start=1):
        detail = f"{e.get('color') or '未关联色块'}  {e.get('name', '')}"
        if e.get("kind_hint"):
            detail += f"  kind_hint={e['kind_hint']}"
        if e.get("matched_pixels") is not None:
            detail += f"  命中={e['matched_pixels']}px"
        if e.get("matched_pixels_plot") is not None:
            detail += f"（剔除色块后 {e['matched_pixels_plot']}px）"
        rows.append((f"图例 {i}", detail))

    fd = d.get("fallback_detail") or {}
    if fd.get("region_colors"):
        rows.append(("图内实际主色", "、".join(
            f"{c['color']}({c['pixels']}px)" for c in fd["region_colors"])))
    if fd.get("used_colors"):
        rows.append(("本次实际使用", "、".join(str(c) for c in fd["used_colors"])))
    if d.get("fallback"):
        rows.append(("回退说明", d["fallback"]))
    if d.get("note"):
        rows.append(("备注", d["note"]))
    return rows


def legend_header(legend) -> str:
    d = _legend_dict(legend)
    return "图例" if d.get("found") else "图例（未检出）"


def legend_csv_lines(legend, comment: str = "#") -> list[str]:
    """图例区块 → CSV 注释行（写在数据之前）。"""
    out = [f"{comment} {_LEGEND_TITLE}"]
    out.append(f"{comment}   来源: {legend_source_text(legend)}")
    for k, v in legend_rows(legend):
        out.append(f"{comment}   {k}: {v}")
    return out


# ------------------------------------------------------------------ 辅助


def _audit_rows(audit) -> list[tuple[str, object]]:
    """把审核记录摊平为 (字段, 值) 行，供 XLSX 元数据表使用。

    字段顺序刻意把「警告」放在最后，便于调用方对尾部行做高亮。
    """
    from .audit import SOURCE_EXPLICIT

    rows: list[tuple[str, object]] = []
    for a in (audit.x, audit.y):
        suffix = "" if a.source == SOURCE_EXPLICIT else "（默认值，未显式声明）"
        rows.append((f"{a.axis} 轴尺度", f"{a.scale}{suffix}"))
        rows.append((f"{a.axis} 轴范围", f"[{_fmtv(a.vmin)}, {_fmtv(a.vmax)}]"))
        detail = f"检出刻度 {a.n_ticks} 个，间距{a.pattern_text}"
        if a.step_text is not None:
            detail += f"，每格≈{a.step_text}"
        rows.append((f"{a.axis} 轴刻度校验", detail))
        if a.tick_values_text is not None:
            rows.append((f"{a.axis} 轴刻度值（按当前标定换算）", a.tick_values_text))
    rows.append(("人工确认", f"已确认 {audit.confirmed_at}" if audit.confirmed else "未确认"))
    rows.append((
        "输出可用性",
        "已人工确认，可用于下游分析" if audit.confirmed
        else "**未人工确认**，请勿直接用于下游分析或发表",
    ))
    rows.append(("对照方法",
                 "把上面每一个「按当前标定换算的刻度值」与图中同位置印的数字对齐；任一对不上"
                 "即说明尺度或范围有误（先查 ×10ⁿ 量级标注与单位）"))
    if audit.warnings:
        for i, w in enumerate(audit.warnings, start=1):
            rows.append((f"警告 {i}", w))
    else:
        rows.append(("警告", "无（几何校验未发现不一致）"))
    return rows


def _fmtv(v: float) -> str:
    if v == 0:
        return "0"
    a = abs(v)
    if a >= 1e4 or a < 1e-3:
        return f"{v:.6g}"
    return f"{v:g}"


def _num(v: object) -> object:
    if isinstance(v, float):
        s = f"{v:.10g}"
        return s
    return v


def _slug(name: str) -> str:
    keep = [c if (c.isalnum() or c in "-_") else "_" for c in name.strip()]
    s = "".join(keep).strip("_")
    return s or "series"


def _sheet_name(name: str, existing: Sequence[str]) -> str:
    base = _slug(name)[:28] or "series"
    cand, i = base, 1
    while cand in existing:
        i += 1
        cand = f"{base[:26]}_{i}"
    return cand


def summarize(series: Sequence[DigitizedSeries]) -> str:
    """生成人类可读的提取摘要。"""
    lines = []
    for s in series:
        if not s.n:
            lines.append(f"  {s.name}: 空序列")
            continue
        xs, ys = s.x, s.y
        extra = ""
        if s.yerr_low is not None and s.yerr_low:
            extra = f"  平均误差 ±{sum(s.yerr_low) / len(s.yerr_low):.4g}"
        lines.append(
            f"  {s.name} [{s.kind}]: {s.n} 点  "
            f"x∈[{min(xs):.6g}, {max(xs):.6g}]  y∈[{min(ys):.6g}, {max(ys):.6g}]{extra}"
        )
    return "\n".join(lines)
